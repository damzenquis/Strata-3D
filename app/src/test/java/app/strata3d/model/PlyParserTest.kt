package app.strata3d.model

import org.junit.Assert.assertEquals
import org.junit.Assert.assertThrows
import org.junit.Test
import java.io.ByteArrayInputStream
import java.nio.ByteBuffer
import java.nio.ByteOrder

class PlyParserTest {

    private val cubeVertices = arrayOf(
        floatArrayOf(0f, 0f, 0f), floatArrayOf(10f, 0f, 0f), floatArrayOf(10f, 10f, 0f), floatArrayOf(0f, 10f, 0f),
        floatArrayOf(0f, 0f, 10f), floatArrayOf(10f, 0f, 10f), floatArrayOf(10f, 10f, 10f), floatArrayOf(0f, 10f, 10f),
    )

    private val cubeFaces = arrayOf(
        intArrayOf(0, 2, 1), intArrayOf(0, 3, 2),
        intArrayOf(4, 5, 6), intArrayOf(4, 6, 7),
        intArrayOf(0, 1, 5), intArrayOf(0, 5, 4),
        intArrayOf(2, 3, 7), intArrayOf(2, 7, 6),
        intArrayOf(1, 2, 6), intArrayOf(1, 6, 5),
        intArrayOf(3, 0, 4), intArrayOf(3, 4, 7),
    )

    private fun asciiCube(): ByteArray = buildString {
        appendLine("ply")
        appendLine("format ascii 1.0")
        appendLine("comment generated by PlyParserTest")
        appendLine("element vertex 8")
        appendLine("property float x")
        appendLine("property float y")
        appendLine("property float z")
        appendLine("element face 12")
        appendLine("property list uchar int vertex_indices")
        appendLine("end_header")
        cubeVertices.forEach { appendLine("${it[0]} ${it[1]} ${it[2]}") }
        cubeFaces.forEach { appendLine("3 ${it[0]} ${it[1]} ${it[2]}") }
    }.toByteArray(Charsets.US_ASCII)

    private fun binaryCube(littleEndian: Boolean): ByteArray {
        val order = if (littleEndian) ByteOrder.LITTLE_ENDIAN else ByteOrder.BIG_ENDIAN
        val faceRecordSize = 1 + 3 * 4
        val size = 8 * 12 + 12 * faceRecordSize
        val buffer = ByteBuffer.allocate(size).order(order)

        val header = buildString {
            appendLine("ply")
            appendLine("format ${if (littleEndian) "binary_little_endian" else "binary_big_endian"} 1.0")
            appendLine("element vertex 8")
            appendLine("property float x")
            appendLine("property float y")
            appendLine("property float z")
            appendLine("element face 12")
            appendLine("property list uchar int vertex_indices")
            appendLine("end_header")
        }.toByteArray(Charsets.US_ASCII)

        val out = ByteBuffer.allocate(header.size + size).order(ByteOrder.BIG_ENDIAN)
        out.put(header)
        val body = out.slice().order(order)
        cubeVertices.forEach { v -> v.forEach { body.putFloat(it) } }
        cubeFaces.forEach { f ->
            body.put(3.toByte())
            f.forEach { body.putInt(it) }
        }
        return out.array()
    }

    private fun parse(bytes: ByteArray, fileName: String = "model.ply", knownLength: Long = bytes.size.toLong()) =
        ModelParser.parse(ByteArrayInputStream(bytes), fileName, knownLength)

    private fun assertCube(mesh: Mesh) {
        assertEquals(12, mesh.triangleCount)
        assertEquals(36 * 3, mesh.vertices.limit())
        assertEquals(10f, mesh.bounds.sizeX, 1e-4f)
        assertEquals(10f, mesh.bounds.sizeY, 1e-4f)
        assertEquals(10f, mesh.bounds.sizeZ, 1e-4f)
        assertEquals(1000.0, mesh.stats.volume, 1e-2)
        assertEquals(600.0, mesh.stats.surfaceArea, 1e-2)
    }

    @Test
    fun parsesAscii() = assertCube(parse(asciiCube()))

    @Test
    fun parsesBinaryLittleEndian() = assertCube(parse(binaryCube(littleEndian = true)))

    @Test
    fun parsesBinaryBigEndian() = assertCube(parse(binaryCube(littleEndian = false)))

    @Test
    fun parsesPolygonFan() {
        val pentagon = """
            ply
            format ascii 1.0
            element vertex 5
            property float x
            property float y
            property float z
            element face 1
            property list uchar int vertex_indices
            end_header
            0 0 0
            2 0 0
            3 1 0
            2 2 0
            0 2 0
            5 0 1 2 3 4
        """.trimIndent().toByteArray(Charsets.US_ASCII)

        val mesh = parse(pentagon)
        assertEquals(3, mesh.triangleCount)
        assertEquals(3f, mesh.bounds.sizeX, 1e-4f)
        assertEquals(2f, mesh.bounds.sizeY, 1e-4f)
    }

    @Test
    fun sniffsFormatWithoutExtension() {
        assertCube(PlyParser.parse(ByteArrayInputStream(asciiCube())))
        assertCube(PlyParser.parse(ByteArrayInputStream(binaryCube(littleEndian = true))))
    }

    @Test
    fun missingMagicThrows() {
        assertThrows(PlyParseException::class.java) {
            parse("not ply\nformat ascii 1.0\nend_header\n".toByteArray())
        }
    }

    @Test
    fun missingFaceElementThrows() {
        val verticesOnly = """
            ply
            format ascii 1.0
            element vertex 1
            property float x
            property float y
            property float z
            end_header
            0 0 0
        """.trimIndent().toByteArray(Charsets.US_ASCII)
        assertThrows(PlyParseException::class.java) { parse(verticesOnly) }
    }

    @Test
    fun outOfBoundsIndexThrows() {
        val badFace = """
            ply
            format ascii 1.0
            element vertex 1
            property float x
            property float y
            property float z
            element face 1
            property list uchar int vertex_indices
            end_header
            0 0 0
            3 0 1 99
        """.trimIndent().toByteArray(Charsets.US_ASCII)
        assertThrows(PlyParseException::class.java) { parse(badFace) }
    }

    @Test
    fun parsesLittleEndian16BitValues() {
        // int16 coordinates (including negatives), a ushort face-count and ushort indices, all little-endian.
        val header = """
            ply
            format binary_little_endian 1.0
            element vertex 8
            property short x
            property short y
            property short z
            element face 12
            property list ushort ushort vertex_indices
            end_header
        """.trimIndent() + "\n"
        val body = ByteBuffer.allocate(8 * 6 + 12 * 8).order(ByteOrder.LITTLE_ENDIAN)
        cubeVertices.forEach { v -> v.forEach { body.putShort((it - 5f).toInt().toShort()) } }
        cubeFaces.forEach { f ->
            body.putShort(3)
            f.forEach { body.putShort(it.toShort()) }
        }
        val mesh = parse(header.toByteArray(Charsets.US_ASCII) + body.array())
        assertCube(mesh)
        assertEquals(-5f, mesh.bounds.minX, 1e-4f)
        assertEquals(5f, mesh.bounds.maxZ, 1e-4f)
    }
}
